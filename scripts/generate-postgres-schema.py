"""Generate PostgreSQL baseline from a freshly initialized empty desktop schema.
Never point this generator at a production database: only static reference rows are exported.
"""
from pathlib import Path
import sqlite3,re,json
ROOT=Path(__file__).resolve().parents[1]
db=sqlite3.connect(ROOT/'outputs/lan-dev/full-schema-seed.db')
statements=[]
fks=[]
seeds=[]
for table,ddl in db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid"):
    ddl=re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',ddl,flags=re.I)
    ddl=re.sub(r'\bTEXT(\s+NOT NULL)?\s+COLLATE NOCASE\b',r'public.citext\1',ddl,flags=re.I)
    ddl=re.sub(r'\bBLOB\b','BYTEA',ddl,flags=re.I)
    ddl=re.sub(r'\bREFERENCES\s+\w+\s*\([^)]*\)(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:SET NULL|CASCADE|RESTRICT|NO ACTION))*','',ddl,flags=re.I)
    statements.append(ddl)
    for row in db.execute(f'PRAGMA foreign_key_list("{table}")'):
        _,seq,target,source,targetcol,onupdate,ondelete,_=row
        assert seq==0,'Composite FK needs explicit generation'
        fks.append(f'ALTER TABLE "{table}" ADD FOREIGN KEY ("{source}") REFERENCES "{target}"("{targetcol}") ON UPDATE {onupdate} ON DELETE {ondelete} DEFERRABLE INITIALLY DEFERRED')
    if table in {'schema_migrations','roles','users','role_permissions','permissions','material_categories','material_projects','number_rules','system_identity'}:
        cursor=db.execute(f'SELECT * FROM "{table}"')
        cols=[x[0] for x in cursor.description]
        for row in cursor:
            item=dict(zip(cols,row))
            if table=='users':item['password_hash']='__BOOTSTRAP_PASSWORD__'
            seeds.append({'table':table,'values':item})
for name,sql in db.execute("SELECT name,sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"):
    statements.append(sql.replace('COLLATE NOCASE',''))
statements+=fks
out=ROOT/'database/postgresql';out.mkdir(exist_ok=True)
(out/'business-schema.json').write_text(json.dumps({'statements':statements,'seeds':seeds},ensure_ascii=False,indent=2),encoding='utf-8')
print(f'Generated {len(statements)} DDL statements; {len(seeds)} static reference rows')
print(db.execute("SELECT sql FROM sqlite_master WHERE name='system_identity'").fetchone()[0])
