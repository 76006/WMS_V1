"""Generate the typed RPC adapters from the existing public service contracts.
Generated files are committed so a normal CMake build does not require Python.
"""
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
SERVICES=['InventoryService','InspectionService','AttachmentService','ShipmentReceiptService','UserService']
headers={name:(ROOT/'src/services'/f'{name}.h').read_text(encoding='utf-8-sig') for name in SERVICES}
wire='''// Generated by scripts/generate-business-rpc.py. Do not edit by hand.
#pragma once
#include <QJsonArray>
#include <QJsonObject>
#include <QDateTime>
'''+''.join(f'#include "services/{name}.h"\n' for name in SERVICES)+'''
namespace BusinessWire {
template<class T> struct Codec;
template<> struct Codec<QString> { static QJsonValue put(const QString &v){return v;} static QString get(const QJsonValue &v){return v.toString();} };
template<> struct Codec<bool> { static QJsonValue put(bool v){return v;} static bool get(const QJsonValue &v){return v.toBool();} };
template<> struct Codec<int> { static QJsonValue put(int v){return v;} static int get(const QJsonValue &v){return v.toInt();} };
template<> struct Codec<qlonglong> { static QJsonValue put(qlonglong v){return QString::number(v);} static qlonglong get(const QJsonValue &v){return v.isString()?v.toString().toLongLong():static_cast<qlonglong>(v.toDouble());} };
template<> struct Codec<double> { static QJsonValue put(double v){return v;} static double get(const QJsonValue &v){return v.isString()?v.toString().toDouble():v.toDouble();} };
template<> struct Codec<QDate> { static QJsonValue put(const QDate &v){return v.toString(Qt::ISODate);} static QDate get(const QJsonValue &v){return QDate::fromString(v.toString(),Qt::ISODate);} };
template<> struct Codec<QDateTime> { static QJsonValue put(const QDateTime &v){return v.toString(Qt::ISODateWithMs);} static QDateTime get(const QJsonValue &v){return QDateTime::fromString(v.toString(),Qt::ISODateWithMs);} };
template<> struct Codec<QByteArray> { static QJsonValue put(const QByteArray &v){return QString::fromLatin1(v.toBase64());} static QByteArray get(const QJsonValue &v){return QByteArray::fromBase64(v.toString().toLatin1());} };
template<class T> struct Codec<QList<T>> {
 static QJsonValue put(const QList<T> &v){QJsonArray a;for(const auto &x:v)a.append(Codec<T>::put(x));return a;}
 static QList<T> get(const QJsonValue &v){QList<T> a;for(const auto &x:v.toArray())a.append(Codec<T>::get(x));return a;}
};
template<> struct Codec<QStringList> {
 static QJsonValue put(const QStringList &v){return QJsonArray::fromStringList(v);}
 static QStringList get(const QJsonValue &v){QStringList a;for(const auto &x:v.toArray())a.append(x.toString());return a;}
};
template<> struct Codec<QMap<QString,QString>> {
 static QJsonValue put(const QMap<QString,QString> &v){QJsonObject o;for(auto i=v.begin();i!=v.end();++i)o.insert(i.key(),i.value());return o;}
 static QMap<QString,QString> get(const QJsonValue &v){QMap<QString,QString> m;const auto o=v.toObject();for(auto i=o.begin();i!=o.end();++i)m.insert(i.key(),i.value().toString());return m;}
};
'''
for text in headers.values():
    text=text.split('class ')[0]
    text=re.sub(r'//[^\n]*','',text)
    for match in re.finditer(r'struct\s+(\w+)\s*(?::\s*public\s+(\w+))?\s*\{(.*?)\};',text,re.S):
        name,base,body=match.groups()
        fields=[]
        for field in body.split(';'):
            field=field.split('=')[0].strip()
            if not field:continue
            parsed=re.fullmatch(r'(.+?)\s+(\w+)',field,re.S)
            assert parsed,(name,field)
            fields.append((re.sub(r'\s+',' ',parsed[1]),parsed[2]))
        wire+=f'template<> struct Codec<{name}> {{\n static QJsonValue put(const {name} &v){{\n'
        wire+=f'  QJsonObject o'+(f'=Codec<{base}>::put(v).toObject()' if base else '')+';\n'
        for typ,key in fields:wire+=f'  o.insert("{key}",Codec<{typ}>::put(v.{key}));\n'
        wire+='  return o;\n }\n'
        wire+=f' static {name} get(const QJsonValue &value){{ {name} v; const auto o=value.toObject();\n'
        if base:wire+=f'  static_cast<{base}&>(v)=Codec<{base}>::get(value);\n'
        for typ,key in fields:wire+=f'  if(o.contains("{key}")) v.{key}=Codec<{typ}>::get(o.value("{key}"));\n'
        wire+='  return v;\n }\n};\n'
wire+='}\n'
(ROOT/'src/network/BusinessWire.h').write_text(wire,encoding='utf-8')
dispatch='''// Generated by scripts/generate-business-rpc.py. Do not edit by hand.
#include "server/BusinessRpc.h"
#include "network/BusinessWire.h"
using namespace BusinessWire;
QJsonObject dispatchBusinessRpc(QSqlDatabase db,qlonglong user,const QString &method,const QJsonObject &args)
{
 QString error;
'''
permissions={}
for service,header in headers.items():
    public=header.split('public:')[1].split('private:')[0]
    public=re.sub(r'//[^\n]*','',public)
    for result,method,params in re.findall(r'\b(bool|QStringList|QString|double)\s+(\w+)\s*\((.*?)\)\s*(?:const)?\s*;',public,re.S):
        if method=='displayNameForUser':continue
        parsed=[]
        for p in params.split(','):
            p=p.split('=')[0].strip()
            pm=re.fullmatch(r'(.*?)\s*([A-Za-z_]\w*)',p,re.S)
            assert pm,p
            raw,name=pm.groups()
            typ=re.sub(r'\s+',' ',raw.replace('const','').replace('&','').replace('*','')).strip()
            parsed.append((typ,name,'*' in raw))
        inputs=[(t,n) for t,n,ptr in parsed if not ptr]
        outputs=[(t,n) for t,n,ptr in parsed if ptr and n!='errorMessage']
        qualified=f'{service}.{method}'
        if service=='InventoryService':
            perm='VIEW_INVENTORY' if method in ['loadPostedDocument','reversibleSerialNumbers','previewSerialNumbers','productionRunReceivedQuantity'] else ('POST_PRODUCTION' if 'Production' in method or 'FinishedGoods' in method else 'POST_INVENTORY')
        elif service=='InspectionService':perm='VIEW_INVENTORY' if method.startswith(('read','list','preview')) else 'POST_INVENTORY'
        elif service=='AttachmentService':perm='VIEW_INVENTORY' if method=='loadAttachment' else 'MANAGE_ATTACHMENTS'
        elif service=='UserService':perm='' if method=='changeOwnPassword' else 'MANAGE_USERS'
        else:perm='POST_INVENTORY'
        permissions[qualified]=perm
        dispatch+=f' if(method=="{qualified}") {{\n  {service} service(db,user);\n'
        for t,n in inputs:dispatch+=f'  auto {n}=Codec<{t}>::get(args.value("{n}"));\n'
        for t,n in outputs:dispatch+=f'  {t} {n}{{}};\n'
        callargs=[('&error' if n=='errorMessage' else ('&'+n if ptr else n)) for t,n,ptr in parsed]
        dispatch+=f'  const auto rpcResult=service.{method}('+','.join(callargs)+');\n'
        dispatch+='  if(!error.isEmpty()) return {{"error",error}};\n'
        if result=='bool':dispatch+='  if(!rpcResult) return {{"error",QStringLiteral("操作失败，事务已回滚。")}};\n'
        dispatch+=f'  QJsonObject reply{{{{"result",Codec<{result}>::put(rpcResult)}}}};\n'
        for t,n in outputs:dispatch+=f'  reply.insert("{n}",Codec<{t}>::put({n}));\n'
        dispatch+='  return reply;\n }\n'
        # Inject only a thin transport branch at the start of the original implementation.
        files=list((ROOT/'src/services').glob(service+'*.cpp'))
        found=False
        for path in files:
            content=path.read_text(encoding='utf-8-sig')
            pattern=rf'({result}\s+{service}::{method}\s*\([^{{]*?\)\s*(?:const)?\s*\{{)'
            m=re.search(pattern,content,re.S)
            if not m:continue
            found=True
            if 'RPC '+qualified in content:break
            block=f'\n    // RPC {qualified}\n    if (RemoteBackend::isRemote(m_database)) {{\n        QJsonObject arguments;\n'
            for t,n in inputs:block+=f'        arguments.insert("{n}",BusinessWire::Codec<{t}>::put({n}));\n'
            block+=f'        const auto reply=RemoteBackend::rpc(m_database,"{qualified}",arguments,errorMessage);\n'
            block+='        if(reply.contains("error")) return {};\n'
            for t,n in outputs:block+=f'        if({n}) *{n}=BusinessWire::Codec<{t}>::get(reply.value("{n}"));\n'
            block+=f'        return BusinessWire::Codec<{result}>::get(reply.value("result"));\n    }}\n'
            content=content[:m.end()]+block+content[m.end():]
            if '#include "network/RemoteBackend.h"' not in content:
                content='#include "network/RemoteBackend.h"\n#include "network/BusinessWire.h"\n'+content
            path.write_text(content,encoding='utf-8')
            break
        assert found,qualified
dispatch+=' return {{"error",QStringLiteral("未知业务接口")}};\n}\n'
dispatch+='QString businessPermission(const QString &method) {\n'
for name,perm in permissions.items():dispatch+=f' if(method=="{name}") return "{perm}";\n'
dispatch+=' return "__DENIED__";\n}\n'
(ROOT/'src/server/BusinessRpc.cpp').write_text(dispatch,encoding='utf-8')
print(f'Generated {len(permissions)} typed service adapters')
